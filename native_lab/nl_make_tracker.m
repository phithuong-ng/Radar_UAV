function tracker=nl_make_tracker(m,d,c)
c=nl_tracking_defaults(c);
% d contains sensor metadata only, not ground truth or labels.
f=@(det)nl_init_filter(det,m.init,c);
volume=prod(diff(d.bounds,1,2));
kappa=d.lambda_effective/volume*c.clutter_density_scale;
birthDensity=c.birth_rate_per_second*d.dt/volume;
if m.frame=="spherical"
 % Scalar native APIs cannot encode the complete nonuniform clutter field.
 % Convert at the reference range; do NOT mix m^-3 with deg^-2 m^-1.
 jac=d.reference_range_m^2*cosd(d.reference_elevation_deg)*(pi/180)^2;
 kappa=kappa*jac;birthDensity=birthDensity*jac;
end
ns=1;if isfield(d,'num_sensors'),ns=d.num_sensors;end
cap=c.max_tracks;gate=c.assignment_threshold;coarse=c.coarse_gate_multiplier*gate;
switch m.tracker
 case "GNN"
  if strcmp(c.gnn_logic,'Score'),conf=c.score_confirmation;del=c.score_deletion;
  else,conf=c.confirmation_history(:)';del=c.deletion_history(:)';end
  tracker=trackerGNN('FilterInitializationFcn',f,'Assignment',c.gnn_assignment, ...
   'AssignmentThreshold',[gate coarse],'TrackLogic',c.gnn_logic, ...
   'ConfirmationThreshold',conf,'DeletionThreshold',del, ...
   'MaxNumTracks',cap,'MaxNumSensors',ns);
  if strcmp(c.gnn_logic,'Score')
   tracker.DetectionProbability=c.pd_assumed;tracker.FalseAlarmRate=-expm1(-max(kappa,1e-12));
   tracker.Volume=1;tracker.Beta=birthDensity;
  end
  if strcmp(c.gnn_assignment,'Custom'),tracker.CustomAssignmentFcn=c.custom_assignment_fcn;end
 case "JPDA"
  events=c.jpda_max_events;if ischar(events)||isstring(events),events=Inf;end
  if strcmp(c.jpda_logic,'Integrated'),conf=c.existence_confirmation;del=c.existence_deletion;
  else,conf=c.confirmation_history(:)';del=c.deletion_history(:)';end
  tracker=trackerJPDA('FilterInitializationFcn',f,'AssignmentThreshold',[gate coarse], ...
   'MaxNumEvents',events,'TrackLogic',c.jpda_logic, ...
   'ConfirmationThreshold',conf,'DeletionThreshold',del, ...
   'DetectionProbability',c.pd_assumed,'ClutterDensity',max(kappa,1e-12), ...
   'MaxNumTracks',cap,'MaxNumSensors',ns);
  if strcmp(c.jpda_logic,'Integrated')
   tracker.NewTargetDensity=birthDensity;tracker.DeathRate=c.phd_death_rate;
  end
 case "TOMHT"
  tracker=trackerTOMHT('FilterInitializationFcn',f, ...
   'AssignmentThreshold',[.3*gate .7*gate gate coarse], ...
   'MaxNumHypotheses',c.tomht_max_hypotheses,'MaxNumTrackBranches',c.tomht_max_branches, ...
   'MaxNumHistoryScans',c.tomht_history_scans,'ConfirmationThreshold',c.tomht_confirmation, ...
   'DeletionThreshold',c.tomht_deletion,'DetectionProbability',c.pd_assumed, ...
   'FalseAlarmRate',-expm1(-max(kappa,1e-12)),'Volume',1,'Beta',birthDensity, ...
   'MaxNumTracks',cap,'MaxNumSensors',ns);
 case "PHD"
  if contains(m.init,'cagmphd'),pos=[1 4 7];else,pos=[1 3 5];end
  phdInit=@(varargin)init_tuned_phd(m.init,c,varargin{:});
  config=trackingSensorConfiguration(1,'IsValidTime',true, ...
   'FilterInitializationFcn',phdInit,'SensorTransformFcn',@phd_sensor_xyz, ...
   'SensorTransformParameters',struct('position_indices',pos), ...
   'SensorLimits',d.bounds,'SensorResolution',[10;10;10],'MaxNumDetsPerObject',1, ...
   'DetectionProbability',c.pd_assumed,'ClutterDensity',max(kappa,1e-12));
  ids=1:ns;if isfield(d,'sensor_ids'),ids=d.sensor_ids;end
  configs=cell(1,numel(ids));
  for j=1:numel(ids),configs{j}=clone(config);configs{j}.SensorIndex=ids(j);end
  tracker=trackerPHD('SensorConfigurations',configs,'BirthRate',c.birth_rate_per_second, ...
   'DeathRate',c.phd_death_rate,'MaxNumTracks',cap,'MaxNumComponents',c.phd_max_components, ...
   'ExtractionThreshold',c.phd_extraction,'ConfirmationThreshold',c.phd_confirmation, ...
   'DeletionThreshold',c.phd_deletion_threshold,'MergingThreshold',c.phd_merging_threshold, ...
   'AssignmentThreshold',c.phd_birth_assignment_threshold);
 otherwise,error('Unknown tracker %s',m.tracker);
end
tracker=nl_apply_properties(tracker,c.tracker_properties_json,'tracker');
end
